export function durationText(min: number): string {
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h === 0) return `${m} мин`;
  if (m === 0) return `${h} ч`;
  return `${h} ч ${m} мин`;
}

export function levelBadge(level: Level): { label: string; color: string } {
  switch (level) {
    case "Начальный":
      return { label: "Начальный", color: "#0f766e" };
    case "Средний":
      return { label: "Средний", color: "#1d4ed8" };
    case "Продвинутый":
      return { label: "Продвинутый", color: "#b91c1c" };
  }
}
